#!/usr/bin/env node

// Bakes the Search Console service account into the server bundle at build time.
// The full GSC_SERVICE_ACCOUNT_JSON (~2.3KB) pushes the function env past AWS
// Lambda's 4KB limit, so it should be scoped to "Builds" only in Netlify and
// read here instead of at runtime. Only client_email + private_key are kept.
import fs from 'fs'
import path from 'path'

const outFile = path.resolve('server/generated/gsc-credentials.ts')

function parse(raw) {
  try {
    return JSON.parse(raw)
  } catch {
    try {
      return JSON.parse(Buffer.from(raw, 'base64').toString('utf8'))
    } catch {
      return null
    }
  }
}

const raw = String(process.env.GSC_SERVICE_ACCOUNT_JSON || '').trim()
const parsed = raw ? parse(raw) : null
const clientEmail = String(parsed?.client_email || '').trim()
const privateKey = String(parsed?.private_key || '').trim()
const account = clientEmail && privateKey ? { clientEmail, privateKey } : null

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(
  outFile,
  `// Generated by scripts/write-gsc-credentials.mjs — do not edit or commit.\n` +
    `export const bundledGscServiceAccount: { clientEmail: string; privateKey: string } | null = ${JSON.stringify(account)}\n`,
)

console.log(account ? '🔑 Bundled GSC service account credentials' : 'ℹ️  No GSC_SERVICE_ACCOUNT_JSON at build time; skipping')
